from extra import EXTRA
from exclude import EXCLUDE
for _k, _v in EXTRA.items():
    ITEMS[_k] = ITEMS.get(_k, "") + "\n" + _v

FLAG_RE = re.compile(r"^(nofreeze|freeze|track=false)$")
HIRA_RE = re.compile(r"^[ぁ-ゖー]+$")


def norm(s):
    s = unicodedata.normalize("NFKC", s)
    s = "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in s)
    return re.sub(r"[\s*＊・()（）/]", "", s)


def main(out_dir):
    foods = []
    for c in CORE:
        cat = CATEGORIES[c["category"]]
        foods.append({
            "id": c["id"], "name": c["name"], "reading": c["reading"], "keywords": c["keywords"],
            "category": c["category"], "fridge_days": cat["fridge_days"], "freezer_days": 14 if cat["freezable"] else None,
            "freezable": cat["freezable"], "track_expiry": cat["track_expiry"],
            "freeze_action": c.get("freeze_action"), "freeze_seconds": c.get("freeze_seconds"),
            "quick_use": None, "core": True, "source": cat["source"],
        })
    seq = 1
    errors = []
    for cat_id, block in ITEMS.items():
        cat = CATEGORIES[cat_id]
        for line in block.strip().splitlines():
            if not line.strip():
                continue
            parts = [p.strip() for p in line.split("|")]
            name, reading = parts[0], parts[1]
            extra, flags = [], []
            for p in parts[2:]:
                if FLAG_RE.match(p):
                    flags.append(p)
                elif p:
                    extra += [k.strip() for k in p.split(",") if k.strip()]
            if not HIRA_RE.match(reading):
                errors.append(f"よみが ひらがなでない: {name} / {reading}")
            freezable = cat["freezable"]
            track = cat["track_expiry"]
            if "nofreeze" in flags: freezable = False
            if "freeze" in flags: freezable = True
            if "track=false" in flags: track = False
            kws = []
            for k in [re.sub(r"（.*?）", "", name)] + extra:
                if k and k not in kws:
                    kws.append(k)
            meat_fish = cat_id in ("ground_poultry", "sliced_meat", "fish", "shellfish", "raw_sausage", "processed_meat", "bacon")
            foods.append({
                "id": f"food_{seq:04d}", "name": name, "reading": reading, "keywords": kws,
                "category": cat_id, "fridge_days": cat["fridge_days"] if track else None,
                "freezer_days": 14 if (freezable and track) else None,
                "freezable": bool(freezable and track), "track_expiry": track,
                "freeze_action": "パックのまま冷凍庫へ" if (freezable and track and meat_fish) else None,
                "freeze_seconds": 30 if (freezable and track and meat_fish) else None,
                "quick_use": None, "core": False,
            })
            seq += 1
    # 明らかに冷蔵・冷凍で保存しない品目を取り除く（番号を振ったあとなので、残った品目の id は変わらない）
    unknown = EXCLUDE - {f["name"] for f in foods}
    if unknown:
        errors.append(f"exclude.py にあるが食材表にない品目: {sorted(unknown)}")
    # 取り除いた品目の名前とキーワードは excluded.json に残す。照合で「冷蔵・冷凍しないもの」と分かるように
    # （残すと「サラダ油」が「サラダ（惣菜）」に当たる、といった取り違えを防ぐ）
    excluded = [{"name": f["name"], "keywords": f["keywords"]} for f in foods if f["name"] in EXCLUDE]
    foods = [f for f in foods if f["name"] not in EXCLUDE]
    # duplicates
    names = Counter(f["name"] for f in foods)
    for n, k in names.items():
        if k > 1:
            errors.append(f"品名の重複: {n} x{k}")
    # keyword collisions (same normalized keyword pointing to different foods) — report only
    kw_owner = {}
    collisions = []
    for f in foods:
        for k in f["keywords"]:
            nk = norm(k)
            if nk in kw_owner and kw_owner[nk] != f["id"]:
                collisions.append((k, kw_owner[nk], f["id"]))
            else:
                kw_owner[nk] = f["id"]
    by_cat = Counter(f["category"] for f in foods)
    cats_out = [{"id": k, **v} for k, v in CATEGORIES.items()]
    json.dump(foods, open(f"{out_dir}/foods.json", "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    json.dump(cats_out, open(f"{out_dir}/categories.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(excluded, open(f"{out_dir}/excluded.json", "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print("total", len(foods))
    for k, v in by_cat.items():
        print(f"  {k}: {v}")
    print("errors", len(errors))
    for e in errors: print("  ", e)
    print("keyword collisions", len(collisions))
    for c in collisions[:80]: print("  ", c)


if __name__ == "__main__":
    main(sys.argv[1])
